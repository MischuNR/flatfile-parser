// all cross field checks were generated by claude. Comments added by me.
export const posCrossFieldChecks: CrossFieldRule<PosDocFields>[] = [
    {
        fieldName: FIELD_NAME.OPOBEM,
        dependsOnFields: [FIELD_NAME.OPOMOB],
        // Läuft einmal pro Satz. Mindestens eines der beiden Mengenfelder muss gesetzt sein.
        check: (bem, {OPOMOB}) =>
            !bem && !OPOMOB
                ? 'Es muss entweder OPOBEM oder OPOMOB gesetzt sein.'
                : null,
    },
    {
        fieldName: FIELD_NAME.OPOBEE,
        dependsOnFields: [FIELD_NAME.OPOBEM],
        check: (unit, {OPOBEM}) =>
            !unit && OPOBEM && toNumber(OPOBEM) > 0
                ? 'Die Mengeneinheit fehlt, obwohl OPOBEM grösser als 0 ist.'
                : null,
    },
    {
        fieldName: FIELD_NAME.OPOPOB,
        dependsOnFields: [
            FIELD_NAME.OPOBEM,
            FIELD_NAME.OPOEIP,
            FIELD_NAME.OPOEIPB,
            FIELD_NAME.OPOGZA,
        ],
        check: (pob, {OPOBEM, OPOEIP, OPOEIPB, OPOGZA}) => {
            // With any fields missing the test is unnecessary.
            if (!pob || !OPOBEM || !OPOEIP || !OPOEIPB) {
                return null;
            }

            const priceBase = toNumber(OPOEIPB);
            if (priceBase === 0) {
                return 'Kann nicht berechnet werden, weil OPOEIPB 0 ist.';
            }

            // OPOGZA is optional. I assume not set means 0
            const surcharge = OPOGZA ? toNumber(OPOGZA) : 0;

            // OPOPOB = (OPOBEM * (OPOEIP / OPOEIPB)) + OPOGZA
            const expected = toNumber(OPOBEM) * (toNumber(OPOEIP) / priceBase) + surcharge;

            // Floats are inexact and the example file rounds to 2 decimals, so we allow a small tolerance.
            const isSame = Math.abs(toNumber(pob) - expected) < 0.005;

            return isSame
                ? null
                : `Der Positionsbetrag stimmt nicht. Erwartet ${expected.toFixed(2)}, gefunden ${pob}.`;
        },
    },
];

