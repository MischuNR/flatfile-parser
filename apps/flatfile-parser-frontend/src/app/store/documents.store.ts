import {computed, inject} from '@angular/core';
import {patchState, signalStore, withComputed, withMethods, withState} from '@ngrx/signals';
import {rxMethod} from '@ngrx/signals/rxjs-interop';
import {delay, pipe, switchMap, tap} from 'rxjs';
import {Doc, FIELD_NAME, HeadDocFields} from 'shared';
import {DocumentsService} from '../services/documents.service';
import {isApiError} from '../utils/is-api-error';
import {initialState} from './documents.state';
import {STATUS_FILTER} from '../types/status-filter';

// fields for recipient filter
// OHTLN1 to OHTLN5: name of the goods receiver
// OHTIDP: GLN of the goods receiver
// OHTIIV: GLN of the invoice receiver
const recipientFields: HeadDocFields[] = [
    FIELD_NAME.OHTLN1,
    FIELD_NAME.OHTLN2,
    FIELD_NAME.OHTLN3,
    FIELD_NAME.OHTLN4,
    FIELD_NAME.OHTLN5,
    FIELD_NAME.OHTIDP,
    FIELD_NAME.OHTIIV,
    FIELD_NAME.OHTRCP,
] as const;

// generated by claude. Modified by me.
export const DocumentsStore = signalStore(
    {providedIn: 'root'},
    withState(initialState),

    withComputed(({documents, statusFilter, recipientFilter, documentNumberFilter}) => ({
        filteredDocuments: computed((): Doc[] => {
            const docs = documents();
            const recipient = recipientFilter().toLowerCase();
            const documentNumberText = documentNumberFilter().toLowerCase();

            return docs.filter((doc) => {
                const matchesStatus =
                    statusFilter() === 'ALL' || (statusFilter() === 'OK') === doc.isSuccess;
                const matchesRecipient =
                    !recipient ||
                    recipientFields.some((field) =>
                        (doc.data?.[field] ?? '').toLowerCase().includes(recipient),
                    );
                const matchesSearch =
                    !documentNumberText || (doc.data?.OHTDON ?? '').toLowerCase().includes(documentNumberText);
                return matchesStatus && matchesRecipient && matchesSearch;
            });
        }),
    })),

    withMethods((store, api = inject(DocumentsService)) => ({
        setStatusFilter: (statusFilter: STATUS_FILTER) => patchState(store, {statusFilter}),
        setRecipientFilter: (recipientFilter: string) => patchState(store, {recipientFilter}),
        setDocumentNumberFilter: (documentNumberFilter: string) => patchState(store, {documentNumberFilter}),
        clearUploadError: () => patchState(store, {uploadError: null}),

        upload: rxMethod<File>(
            pipe(
                tap(() => patchState(store, {isUploading: true, uploadError: null})),
                switchMap((file) => api.uploadDocument(file)),
                tap((result) => {
                    if (isApiError(result)) {
                        patchState(store, {isUploading: false, uploadError: result});
                        return;
                    }
                    const current = store.documents();
                    patchState(store, {
                        isUploading: false,
                        documents: [...current, ...result],
                    });
                }),
            ),
        ),

        load: rxMethod<void>(
            pipe(
                tap(() => patchState(store, {isLoadingDocuments: true, loadDocumentsError: null})),
                switchMap(() => api.getAllDocuments()),
                tap((result) => {
                    if (isApiError(result)) {
                        patchState(store, {isLoadingDocuments: false, loadDocumentsError: result});
                        return;
                    }
                    patchState(store, {documents: result, isLoadingDocuments: false});
                }),
            ),
        ),
    })),
);